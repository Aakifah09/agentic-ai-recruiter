import streamlit as st

from recruiter.prompts import PROMPT_VERSION

st.title("How it works", anchor=False)

st.markdown(
    """
The recruiter assistant is a **controlled multi-agent workflow**: each agent has one job, a validated
Pydantic output, and a deterministic fallback, and an orchestrator runs them in a fixed order with a full trace.
"""
)

st.markdown(
    """
```mermaid
flowchart LR
    JD[Job description] --> A1[1 - JD Analyst]
    CV[Resumes PDF/DOCX/TXT] --> R[Redaction] --> A2[2 - Resume Analyst]
    A1 --> A2
    A1 --> A3[3 - Evidence Matcher]
    A2 --> A3 --> RK[Ranker] --> A4[4 - Interview Planner]
    A3 --> A5[5 - Compliance Guardrail]
    A4 --> A5 --> OUT[Shortlist report]
    OUT --> H[Recruiter review + audit log]
    H -. edits job profile / policy .-> A3
```
"""
)

cols = st.columns(2, gap="large")
with cols[0]:
    st.markdown(
        """
**Agents**

| Agent | LLM role | Deterministic role |
|---|---|---|
| JD Analyst | Open-vocabulary skills, priorities | Section parsing, essential vs desirable, "X or Y" alternatives, bias flags |
| Resume Analyst | Skills with verbatim quotes | Redaction, taxonomy match, date-range experience, grounding check |
| Evidence Matcher | Optional narrative | Weighted score, coverage, relevant experience, confidence |
| Interview Planner | Tailored questions | Template questions from evidence and gaps |
| Compliance Guardrail | none | Protected-term filter, grounding, PII leak check |
"""
    )
with cols[1]:
    st.markdown(
        f"""
**Design choices**

- **Scores are never generated by the LLM.** They are computed from an evidence table, so they are reproducible and explainable.
- **Every LLM claim is grounded.** Quotes that do not appear in the resume are discarded.
- **Graceful degradation.** Any LLM timeout or invalid JSON is retried once with the validation error, then falls back to rules.
- **CPU friendly.** LLM use is opt-in per agent; the rule-based mode runs in well under a second per candidate.
- **Human in the loop.** Recruiters edit requirements and weights, re-score instantly and record decisions with an audit trail.
- Prompt set version: `{PROMPT_VERSION}`.
"""
    )

st.warning(
    "This is a portfolio demonstration built on fictional data. Automated screening is regulated in many places "
    "(for example the EU AI Act treats recruitment AI as high-risk, and NYC Local Law 144 requires bias audits). "
    "Real deployments need legal review, bias audits on real data and transparent candidate notices.",
    icon=":material/policy:",
)
